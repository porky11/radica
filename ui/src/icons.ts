/**
 * Returns an inline SVG string for the specified icon.
 */
export function renderIcon(
  name: IconName,
  options?: {
    className?: string;
    size?: number | string;
    ariaLabel?: string;
  }
): string {
  const path = ICON_PATHS[name] || "";
  const cls = ["svg-icon", options?.className].filter(Boolean).join(" ");
  const sizeAttr = options?.size
    ? `width="${options.size}" height="${options.size}"`
    : ``;
  const ariaAttr = options?.ariaLabel
    ? `role="img" aria-label="${options.ariaLabel}"`
    : `aria-hidden="true"`;

  return `<svg viewBox="0 0 24 24" class="${cls}" ${sizeAttr} ${ariaAttr} fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${path}</svg>`;
}
